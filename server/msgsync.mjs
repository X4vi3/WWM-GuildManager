// Приведение УЖЕ отправленных сообщений к тому виду, который рисует текущий код.
//
// Зачем. Анонс собирается заново при каждой перерисовке, поэтому новая вёрстка
// доезжает до канала сама — но только если перерисовку кто-то запустил. Запускало
// её лишь изменение данных (заявка, правка события). Деплой изменением данных не
// является, и после выкатки анонсы висели в старом виде до первого нажатия кнопки,
// а сообщение с кнопкой регистрации — вообще всегда.
//
// Решение — не «номер версии оформления», который надо помнить повышать (забыл =
// тихо ничего не произошло), а ОТПЕЧАТОК отправленного: рядом с каждым сообщением
// храним короткий хеш того, что мы в него последний раз положили. Перед правкой
// собираем содержимое заново и сравниваем. Совпало — в сеть не идём вовсе.
//
// Поэтому проход бесплатный, когда ничего не менялось, и срабатывает сам на любую
// причину расхождения: правку кода, переключение языка бота, загрузку эмодзи школ,
// смену адреса сайта или роли для пинга.

import crypto from 'node:crypto';

// Короткий хеш содержимого сообщения. Порядок ключей стабилен: тело собирает одна
// и та же функция, поэтому JSON.stringify даёт одинаковую строку на одинаковых данных.
//
// ВАЖНО: считать надо ТОЛЬКО содержимое. Всё, что ставится в момент отрисовки,
// вызывающий обязан выбросить сам, иначе отпечаток будет отличаться всегда и правка
// поедет на каждый проход — то есть ровно та беда, ради которой всё и затевалось.
//
// Живой пример: в подвале карточки Discord стоит `timestamp` («обновлено тогда-то»),
// и он новый при каждом вызове. Поэтому discord.mjs считает отпечаток через
// собственный bodyFingerprint, который эту метку срезает. Само время события
// безопасно: оно абсолютное — родные метки <t:unix:F|R> у Discord и готовая строка
// московского времени у Телеграма, обратных отсчётов в теле нет.
export const fingerprint = (payload) =>
  crypto.createHash('sha1').update(JSON.stringify(payload)).digest('base64url').slice(0, 16);

export const RESYNC_MAX_AGE_MS = 24 * 60 * 60 * 1000; // сутки
export const RESYNC_GAP_MS = 400;   // пауза между правками, чтобы не влететь в 429
export const RESYNC_DELAY_MS = 5000; // не лезем в сеть в первую секунду после старта

// Стоит ли подновлять сообщение события. Прошедшее давно не трогаем: пролистывать
// туда никто не будет, а лимиты правок общие с живыми анонсами.
export const worthResync = (startsAt, now = Date.now(), maxAgeMs = RESYNC_MAX_AGE_MS) => {
  if (!startsAt) return true;                    // без времени не знаем — лучше обновить
  const t = new Date(startsAt).getTime();
  if (!Number.isFinite(t)) return true;
  return t >= now - maxAgeMs;
};
