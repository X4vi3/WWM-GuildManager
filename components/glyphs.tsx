interface Props {
  name: GlyphName;
  className?: string;
  title?: string;
}

// Размер по умолчанию — 1.05em, и это не круглое число из ниоткуда. Font Awesome рисует
// бокс шириной 1.25em при высоте 1em и заполняет его почти целиком (замерено: при шрифте
// 12px у него 15 на 12 пикселей). Наш глиф после подгонки viewBox заполняет свой бокс
// полностью, поэтому для совпадения чернил боксу хватает небольшой добавки — иначе глиф
// выглядит уже крупнее соседних стоковых.
//
// Цвет — currentColor, как у текста. `inline-block align-[-0.125em]` ставит глиф на ту же
// линию, где стоял <i> из Font Awesome, иначе строки с иконкой поехали бы вниз.
const Glyph: React.FC<Props> = ({ name, className, title }) => (
  <svg
    viewBox={BOXES[name]}
    fill="currentColor"
    className={`inline-block shrink-0 align-[-0.125em] ${className || 'w-[1.05em] h-[1.05em]'}`}
    role={title ? 'img' : undefined}
    aria-hidden={title ? undefined : true}
  >
    {title && <title>{title}</title>}
    {PATHS[name]}
  </svg>
);

export default Glyph;
