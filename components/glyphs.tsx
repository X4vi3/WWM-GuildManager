// Свои иконки для игровых понятий.
//
// Зачем они вообще. Всё остальное в приложении рисует Font Awesome, и для «закрыть»,
// «плюс» и «корзины» это правильно: такие значки должны быть незаметными и одинаковыми
// везде. Но игровые понятия им рисовать нечем, и стоковый набор подставлял что нашлось:
// босс — дракон из общего каталога, вышка — обсерватория, ранкед — пьедестал (владелец
// сказал прямо: «издалека на фак похоже», и он прав — средний столбик выше соседних).
// Интерфейс говорил про конкретную игру словами чужого стока.
//
// При этом свой язык у приложения уже был — маркеры на карте (`assets/boss.png`,
// `tower_blue.png`, `tree_blue.png`): плоские силуэты с узнаваемой формой. Эти глифы
// обводят их, поэтому бейдж и метка на карте читаются как одно и то же.
//
// Почему инлайновый SVG, а не шрифт: картинку приказа снимает html-to-image, и классы
// Font Awesome туда не доезжают — именно поэтому в экспорте до сих пор стояли эмодзи.
// SVG виден и там, и здесь, и красится через currentColor как обычный текст.
//
// Рисунок ЗАЛИВКОЙ, а не обводкой: маркеры на карте залиты, и обводка рядом с ними
// выглядела бы из другого набора. Проверялось на 12, 16 и 24 пикселях — мелкие детали
// (глаза дракона, ступени пагоды) на 12 сливаются, но силуэт опознаётся, а это и есть
// работа иконки такого размера.

export type GlyphName = 'boss' | 'tower' | 'jungle' | 'prak' | 'ranked' | 'league';

// Свой viewBox у каждого глифа, подогнанный под фактические границы его рисунка.
//
// Общий 0 0 24 24 выглядел разумно и был прямой ошибкой: доля бокса, которую занимает
// рисунок, у всех разная — у мишени 92 процента, у шевронов 67 по высоте, у дерева 74
// по ширине. На экране это читается как «босс и лес в полтора раза меньше остальных»,
// что владелец и увидел. У Font Awesome такой беды нет: там каждый глиф подогнан под
// свою рамку заранее.
//
// Рамка КВАДРАТНАЯ и центрирована на рисунке: подгонка по фактическим сторонам растянула
// бы шевроны по вертикали. Значения посчитаны из getBBox, а не подобраны на глаз, —
